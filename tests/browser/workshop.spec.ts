import { test, expect } from '@playwright/test'

test('Мастерская: этажи, колонны, лестницы, перегородки, экспорт, сохранение', async ({page}) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/workshop.html')
  await expect(page.getByRole('heading', {name:'Мой дом мечты'})).toBeVisible()
  await expect(page.locator('#volume canvas')).toBeVisible()
  await page.locator('#roofSwitch').click()
  await expect(page.locator('#roofSwitch')).toHaveText('Крыша: нет')
  await page.locator('#cutaway').click()
  await expect(page.locator('#cutaway')).toHaveAttribute('aria-pressed','true')
  await page.locator('#cutaway').click()
  await page.locator('#roofSwitch').click()
  await page.locator('#add').click()
  await expect(page.locator('#floorStat')).toHaveText('2')
  await page.locator('#x0').fill('4')
  await page.locator('#x0').dispatchEvent('change')
  await expect(page.locator('#columns')).not.toHaveText('0')
  await expect(page.locator('[data-overhang="true"]')).toHaveCount(0)
  await page.locator('[data-floor="0"]').click()
  await expect(page.locator('[data-overhang="true"]')).toHaveCount(1)
  await expect(page.locator('[data-support="true"]').first()).toBeVisible()
  await page.locator('[data-tool="stairs"]').click()
  await page.locator('#stairKind').selectOption('spiral')
  await page.locator('[data-stair-node="4,1"]').click()
  await expect(page.locator('[data-stair-kind="spiral"]')).toHaveCount(1)
  await page.locator('#stairKind').selectOption('straight')
  await expect(page.locator('[data-stair-kind="straight"]')).toHaveCount(1)
  await expect(page.locator('#checks')).toContainText('Проект удовлетворяет требованиям геометрии')
  await page.locator('[data-tool="partition"]').click()
  await page.locator('[data-node="4,4"]').click()
  await page.locator('[data-node="4,6"]').click()
  await expect(page.locator('.partition')).toHaveCount(1)
  // Adjacent glazing segments form one 2-metre panoramic window in 2D and 3D.
  await page.locator('[data-tool="window"]').click()
  await page.locator('[data-wall="f0a"][data-offset="1.5"]').click()
  await page.locator('[data-wall="f0a"][data-offset="2.5"]').click()
  await expect(page.locator('[data-opening-span="window"][data-span-width="2"]')).toHaveCount(1)
  await page.locator('#undo').click()
  await expect(page.locator('[data-opening-span="window"][data-span-width="2"]')).toHaveCount(0)
  await page.locator('#redo').click()
  await expect(page.locator('[data-opening-span="window"][data-span-width="2"]')).toHaveCount(1)
  await page.locator('#undo').click()
  await page.locator('#undo').click()
  await page.locator('#undo').click()
  await expect(page.locator('.partition')).toHaveCount(0)
  await page.locator('#redo').click()
  await expect(page.locator('.partition')).toHaveCount(1)
  await page.reload()
  await expect(page.locator('#floorStat')).toHaveText('2')
  await page.locator('[data-floor="0"]').click()
  await expect(page.locator('.partition')).toHaveCount(1)
  expect(errors).toEqual([])
})

test('Свободная мастерская не меняет сохранения главы I', async ({page}) => {
  await page.goto('/')
  await page.locator('[data-action="new"]').click()
  const city = await page.evaluate(() => localStorage.getItem('architects-of-time.valley'))
  await page.goto('/workshop.html')
  await page.locator('#add').click()
  await page.locator('#w').fill('5')
  await page.locator('#w').dispatchEvent('change')
  expect(await page.evaluate(() => localStorage.getItem('architects-of-time.valley'))).toBe(city)
})
