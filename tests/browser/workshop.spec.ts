test('Оформление дома: стеклянная веранда сохраняется и экспортируется', async ({page}) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/workshop.html')
  const style=page.getByRole('combobox',{name:'Стиль дома'})
  await expect(style).toHaveValue('classic')
  await style.selectOption('modern')
  await expect(style).toHaveValue('modern')
  let saved=await page.evaluate(() => JSON.parse(localStorage.getItem('avi-architect.multistorey-workshop.v1')||'null'))
  expect(saved?.style).toBe('modern')
  await page.locator('#add').click()
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('avi-architect.multistorey-workshop.v1')||'null')?.style)).toBe('modern')
  await page.reload()
  await expect(page.getByRole('combobox',{name:'Стиль дома'})).toHaveValue('modern')
  await page.getByRole('combobox',{name:'Стиль дома'}).selectOption('classic')
  saved=await page.evaluate(() => JSON.parse(localStorage.getItem('avi-architect.multistorey-workshop.v1')||'null'))
  expect(saved?.style).toBe('classic')
  expect(errors).toEqual([])
})

test('Мобильная мастерская: план первым, панель и подменю инструментов', async ({page}) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({width:390,height:844})
  await page.goto('/workshop.html?mode=career&quest=landmark')

  await expect(page.locator('.dimensions-section')).toBeHidden()
  await expect(page.locator('#careerReview')).toBeVisible()
  const positions=await page.evaluate(() =>
    ['.plan-panel','.tools-section','#careerReview','.floors-section']
      .map(selector => document.querySelector(selector)!.getBoundingClientRect().top))
  expect(positions).toEqual([...positions].sort((a,b)=>a-b))

  const tools=page.locator('#tools')
  await expect(tools.locator('button:visible')).toHaveCount(5)
  const walls=tools.locator('[data-tool-group="walls"]')
  await walls.click()
  await expect(walls).toHaveAttribute('aria-expanded','true')
  await expect(tools.locator('[data-tool="outline"]')).toBeVisible()
  await tools.locator('[data-tool="partition"]').click()
  await expect(walls).toHaveAttribute('aria-expanded','false')
  await expect(walls).toHaveAttribute('aria-pressed','true')

  const openings=tools.locator('[data-tool-group="openings"]')
  await openings.click()
  await expect(tools.locator('[data-tool="window"]')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(openings).toHaveAttribute('aria-expanded','false')
  await openings.click()
  await tools.locator('[data-tool="window"]').click()
  await expect(openings).toHaveAttribute('aria-pressed','true')

  const stairs=tools.locator('[data-stair-toggle]')
  await stairs.click()
  await expect(stairs).toHaveAttribute('aria-expanded','true')
  await expect(page.locator('#stairKind')).toBeHidden()
  await expect(page.locator('#stairFacing')).toBeHidden()
  await tools.locator('[data-stair-kind="spiral"]').click()
  await tools.locator('[data-stair-facing="east"]').click()
  await expect(tools.locator('[data-stair-kind="spiral"]')).toHaveAttribute('aria-pressed','true')
  await expect(tools.locator('[data-stair-facing="east"]')).toHaveAttribute('aria-pressed','true')
  await expect(page.locator('#stairKind')).toHaveValue('spiral')
  await expect(page.locator('#stairFacing')).toHaveValue('east')
  await stairs.click()
  await expect(stairs).toHaveAttribute('aria-expanded','false')
  await tools.locator('[data-tool="erase"]').click()
  await expect(page.locator('#stairKind')).toBeHidden()
  await expect(tools.locator('button:visible > svg.icon')).toHaveCount(5)

  // The same toolbar must fit a narrow phone; early orders have no stair tool.
  await page.setViewportSize({width:320,height:720})
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
  await page.goto('/workshop.html?mode=career&quest=home')
  await expect(page.locator('#tools button:visible')).toHaveCount(4)
  await expect(page.locator('.dimensions-section')).toBeHidden()
  expect(errors).toEqual([])
})

test('Мобильная лестница: лепестки изменяют существующую конструкцию', async ({page}) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({width:390,height:844})
  await page.goto('/workshop.html')
  await page.locator('#add').click()
  await page.locator('[data-floor="0"]').click()
  const tools=page.locator('#tools')
  await tools.locator('[data-stair-toggle]').click()
  await tools.locator('[data-stair-kind="spiral"]').click()
  await tools.locator('[data-stair-facing="west"]').click()
  await expect(page.locator('#plan [data-stair-kind="spiral"]')).toHaveCount(1)
  expect(await page.evaluate(() => {
    const plan=JSON.parse(localStorage.getItem('avi-architect.multistorey-workshop.v1')||'null')
    return [plan?.floors[0]?.stairToNext?.kind,plan?.floors[0]?.stairToNext?.facing]
  })).toEqual(['spiral','west'])
  await page.reload()
  await page.locator('[data-floor="0"]').click()
  await tools.locator('[data-stair-toggle]').click()
  await expect(tools.locator('[data-stair-kind="spiral"]')).toHaveAttribute('aria-pressed','true')
  await expect(tools.locator('[data-stair-facing="west"]')).toHaveAttribute('aria-pressed','true')
  expect(errors).toEqual([])
})

test('Мобильная шапка: название над компактными действиями, меню, история на плане', async ({page}) => {
  const errors: string[] = []
  page.on('pageerror',error=>errors.push(error.message))
  await page.setViewportSize({width:390,height:844})
  await page.goto('/workshop.html')

  const logo=page.locator('.top .logo')
  const primary=page.locator('.top .header-primary')
  const menu=page.locator('#headerMenuToggle')
  const extra=page.locator('#headerExtra')
  await expect(menu).toBeVisible()
  await expect(page.locator('#publish')).toBeVisible()
  await expect(extra).toBeHidden()
  await expect(page.locator('#undo')).toBeHidden()
  await expect(page.locator('#undoMobile')).toBeVisible()
  await expect(page.locator('#redoMobile')).toBeVisible()
  await expect(page.locator('#undoMobile')).toBeDisabled()
  await expect(page.locator('#redoMobile')).toBeDisabled()

  const positions=await page.evaluate(()=>{
    const box=(s:string)=>document.querySelector(s)!.getBoundingClientRect()
    return {brandBottom:box('.top .logo').bottom,buttonsTop:box('.top .header-primary').top,
      planTop:box('.plan-panel').top,headerBottom:box('.top').bottom,
      undoTop:box('#undoMobile').top,planTitleTop:box('.plan-panel .viewport-head h2').top,
      undoLeft:box('#undoMobile').left,planTitleRight:box('.plan-panel .viewport-head h2').right}
  })
  expect(positions.brandBottom).toBeLessThanOrEqual(positions.buttonsTop)
  expect(positions.headerBottom).toBeLessThan(positions.planTop)
  expect(Math.abs(positions.undoTop-positions.planTitleTop)).toBeLessThan(18)
  expect(positions.planTitleRight).toBeLessThanOrEqual(positions.undoLeft)

  await menu.click()
  await expect(menu).toHaveAttribute('aria-expanded','true')
  await expect(page.locator('#fromCity')).toBeVisible()
  await expect(page.locator('#import')).toBeVisible()
  await expect(page.locator('#export')).toBeVisible()
  await expect(page.locator('#reset')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(menu).toHaveAttribute('aria-expanded','false')
  await expect(extra).toBeHidden()
  await menu.click()
  await page.locator('.top .logo').click()
  await expect(extra).toBeHidden()

  await page.locator('#add').click()
  await expect(page.locator('#floorcount')).toHaveText('2')
  await expect(page.locator('#undoMobile')).toBeEnabled()
  await page.locator('#undoMobile').click()
  await expect(page.locator('#floorcount')).toHaveText('1')
  await expect(page.locator('#redoMobile')).toBeEnabled()
  await page.locator('#redoMobile').click()
  await expect(page.locator('#floorcount')).toHaveText('2')

  await page.setViewportSize({width:320,height:720})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false)
  await expect(page.locator('#headerMenuToggle')).toBeVisible()
  await expect(page.locator('#undoMobile')).toBeVisible()
  expect(errors).toEqual([])
})

