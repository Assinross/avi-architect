import { test, expect } from '@playwright/test'

test('Мастерская: этажи, колонны, лестницы, перегородки, экспорт, сохранение', async ({page}) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/workshop.html')
  await expect(page.getByRole('heading', {name:'Мой дом мечты'})).toBeVisible()
  await expect(page.locator('#volume canvas')).toBeVisible()
  await page.locator('#roofSwitch').click()
  await expect(page.locator('#roofSwitch')).toHaveText('Крыша: нет')
  await page.locator('#cutaway').click()
  await expect(page.locator('#cutaway')).toHaveAttribute('aria-pressed','true')
  await page.locator('#cutaway').click()
  await page.locator('#roofSwitch').click()
  await page.locator('#add').click()
  await expect(page.locator('#floorStat')).toHaveText('2')
  await page.locator('#x0').fill('4')
  await page.locator('#x0').dispatchEvent('change')
  await expect(page.locator('#columns')).not.toHaveText('0')
  await expect(page.locator('[data-overhang="true"]')).toHaveCount(0)
  await page.locator('[data-floor="0"]').click()
  await expect(page.locator('[data-overhang="true"]')).toHaveCount(1)
  await expect(page.locator('[data-support="true"]').first()).toBeVisible()
  await page.locator('[data-tool="stairs"]').click()
  await page.locator('#stairKind').selectOption('spiral')
  await page.locator('[data-stair-node="4,1"]').click()
  await expect(page.locator('[data-stair-kind="spiral"]')).toHaveCount(1)
  await page.locator('#stairKind').selectOption('straight')
  await expect(page.locator('[data-stair-kind="straight"]')).toHaveCount(1)
  await expect(page.locator('#checks')).toContainText('Проект удовлетворяет требованиям геометрии')
  await page.locator('[data-tool="partition"]').click()
  await page.locator('[data-node="4,4"]').click()
  await page.locator('[data-node="4,6"]').click()
  await expect(page.locator('.partition')).toHaveCount(1)
  // Adjacent glazing segments form one 2-metre panoramic window in 2D and 3D.
  await page.locator('[data-tool="window"]').click()
  await page.locator('[data-wall="f0a"][data-offset="1.5"]').click()
  await page.locator('[data-wall="f0a"][data-offset="2.5"]').click()
  await expect(page.locator('[data-opening-span="window"][data-span-width="2"]')).toHaveCount(1)
  await page.locator('#undo').click()
  await expect(page.locator('[data-opening-span="window"][data-span-width="2"]')).toHaveCount(0)
  await page.locator('#redo').click()
  await expect(page.locator('[data-opening-span="window"][data-span-width="2"]')).toHaveCount(1)
  await page.locator('#undo').click()
  await page.locator('#undo').click()
  await page.locator('#undo').click()
  await expect(page.locator('.partition')).toHaveCount(0)
  await page.locator('#redo').click()
  await expect(page.locator('.partition')).toHaveCount(1)
  await page.reload()
  await expect(page.locator('#floorStat')).toHaveText('2')
  await page.locator('[data-floor="0"]').click()
  await expect(page.locator('.partition')).toHaveCount(1)
  expect(errors).toEqual([])
})

test('Свободная мастерская не меняет сохранения главы I', async ({page}) => {
  await page.goto('/')
  await page.locator('[data-action="new"]').click()
  const city = await page.evaluate(() => localStorage.getItem('architects-of-time.valley'))
  await page.goto('/workshop.html')
  await page.locator('#add').click()
  await page.locator('#w').fill('5')
  await page.locator('#w').dispatchEvent('change')
  expect(await page.evaluate(() => localStorage.getItem('architects-of-time.valley'))).toBe(city)
})

test('Оформление дома: стеклянная веранда сохраняется и экспортируется', async ({page}) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/workshop.html')
  const style=page.getByRole('combobox',{name:'Стиль дома'})
  await expect(style).toHaveValue('classic')
  await style.selectOption('modern')
  await expect(style).toHaveValue('modern')
  let saved=await page.evaluate(() => JSON.parse(localStorage.getItem('avi-architect.multistorey-workshop.v1')||'null'))
  expect(saved?.style).toBe('modern')
  await page.locator('#add').click()
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('avi-architect.multistorey-workshop.v1')||'null')?.style)).toBe('modern')
  await page.reload()
  await expect(page.getByRole('combobox',{name:'Стиль дома'})).toHaveValue('modern')
  await page.getByRole('combobox',{name:'Стиль дома'}).selectOption('classic')
  saved=await page.evaluate(() => JSON.parse(localStorage.getItem('avi-architect.multistorey-workshop.v1')||'null'))
  expect(saved?.style).toBe('classic')
  expect(errors).toEqual([])
})

test('Мобильная мастерская: план первым, панель и подменю инструментов', async ({page}) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({width:390,height:844})
  await page.goto('/workshop.html?mode=career&quest=landmark')

  await expect(page.locator('.dimensions-section')).toBeHidden()
  await expect(page.locator('#careerReview')).toBeVisible()
  const positions=await page.evaluate(() =>
    ['.plan-panel','.tools-section','#careerReview','.floors-section']
      .map(selector => document.querySelector(selector)!.getBoundingClientRect().top))
  expect(positions).toEqual([...positions].sort((a,b)=>a-b))

  const tools=page.locator('#tools')
  await expect(tools.locator('button:visible')).toHaveCount(5)
  const walls=tools.locator('[data-tool-group="walls"]')
  await walls.click()
  await expect(walls).toHaveAttribute('aria-expanded','true')
  await expect(tools.locator('[data-tool="outline"]')).toBeVisible()
  await tools.locator('[data-tool="partition"]').click()
  await expect(walls).toHaveAttribute('aria-expanded','false')
  await expect(walls).toHaveAttribute('aria-pressed','true')

  const openings=tools.locator('[data-tool-group="openings"]')
  await openings.click()
  await expect(tools.locator('[data-tool="window"]')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(openings).toHaveAttribute('aria-expanded','false')
  await openings.click()
  await tools.locator('[data-tool="window"]').click()
  await expect(openings).toHaveAttribute('aria-pressed','true')

  await tools.locator('[data-tool="stairs"]').click()
  await expect(page.locator('#stairKind')).toBeVisible()
  await tools.locator('[data-tool="erase"]').click()
  await expect(page.locator('#stairKind')).toBeHidden()
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
  expect(errors).toEqual([])
})
